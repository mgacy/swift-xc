create_fixture() {
    local name="$1"

    FIXTURE_ROOT="$TEST_ROOT/$name"
    FIXTURE_ORIGIN="$FIXTURE_ROOT/origin.git"
    FIXTURE_WORKTREE="$FIXTURE_ROOT/worktree"
    FIXTURE_BIN="$FIXTURE_ROOT/bin"
    FIXTURE_GH_LOG="$FIXTURE_ROOT/gh.log"
    FIXTURE_GH_EDIT_LOG="$FIXTURE_ROOT/gh-edit.log"
    FIXTURE_PR_STATE="$FIXTURE_ROOT/pr-state"
    FIXTURE_OUTPUT="$FIXTURE_ROOT/output.log"
    GH_OPEN_PR_IS_CROSS_REPOSITORY="0"
    GH_CREATE_SIDE_EFFECT_URL=""
    GH_CREATE_SIDE_EFFECT_IS_CROSS_REPOSITORY="0"
    GH_EDIT_FAIL="0"

    mkdir -p "$FIXTURE_BIN"
    git init --bare --quiet "$FIXTURE_ORIGIN"
    git init --quiet --initial-branch=main "$FIXTURE_WORKTREE"
    git -C "$FIXTURE_ORIGIN" symbolic-ref HEAD refs/heads/main
    git -C "$FIXTURE_WORKTREE" config user.name "Release Script Tests"
    git -C "$FIXTURE_WORKTREE" config user.email "release-tests@example.com"
    git -C "$FIXTURE_WORKTREE" config commit.gpgsign false
    git -C "$FIXTURE_WORKTREE" remote add origin "$FIXTURE_ORIGIN"

    mkdir -p "$FIXTURE_WORKTREE/Sources/xc"
    printf '%s\n' \
        '// This file was generated by the `VersionFile` package plugin.' \
        '' \
        'enum Version {' \
        '    static let number = "0.0.1"' \
        '}' \
        > "$FIXTURE_WORKTREE/Sources/xc/Version.swift"
    printf '// fixture\n' > "$FIXTURE_WORKTREE/Package.swift"

    git -C "$FIXTURE_WORKTREE" add Package.swift Sources/xc/Version.swift
    git -C "$FIXTURE_WORKTREE" commit --quiet -m "Initial"
    git -C "$FIXTURE_WORKTREE" push --quiet -u origin main

    write_swift_stub "$FIXTURE_BIN/swift"
    write_gh_stub "$FIXTURE_BIN/gh"
    chmod +x "$FIXTURE_BIN/swift" "$FIXTURE_BIN/gh"
}

run_script() {
    local swift_mode="$1"
    local open_pr_url="$2"
    local create_pr_fails="$3"
    shift 3

    set +e
    (
        cd "$FIXTURE_WORKTREE"
        env \
            PATH="$FIXTURE_BIN:$PATH" \
            SWIFT_TEST_MODE="$swift_mode" \
            GH_TEST_OPEN_PR_URL="$open_pr_url" \
            GH_TEST_OPEN_PR_IS_CROSS_REPOSITORY="$GH_OPEN_PR_IS_CROSS_REPOSITORY" \
            GH_TEST_CREATE_FAIL="$create_pr_fails" \
            GH_TEST_LOG="$FIXTURE_GH_LOG" \
            GH_TEST_EDIT_LOG="$FIXTURE_GH_EDIT_LOG" \
            GH_TEST_PR_STATE="$FIXTURE_PR_STATE" \
            GH_TEST_CREATE_SIDE_EFFECT_URL="$GH_CREATE_SIDE_EFFECT_URL" \
            GH_TEST_CREATE_SIDE_EFFECT_IS_CROSS_REPOSITORY="$GH_CREATE_SIDE_EFFECT_IS_CROSS_REPOSITORY" \
            GH_TEST_EDIT_FAIL="$GH_EDIT_FAIL" \
            "$SCRIPT_PATH" "$@"
    ) > "$FIXTURE_OUTPUT" 2>&1
    LAST_STATUS=$?
    set -e
    LAST_OUTPUT="$(<"$FIXTURE_OUTPUT")"
}

test_happy_path() {
    create_fixture happy-path
    run_script "" "" "0" patch

    assert_equal "0" "$LAST_STATUS" "happy path should succeed" || return 1
    assert_equal "main" "$(git -C "$FIXTURE_WORKTREE" branch --show-current)" "script should return to main" || return 1
    assert_ref_exists "$FIXTURE_WORKTREE" refs/remotes/origin/release "release should be pushed" || return 1
    assert_equal \
        "Bump Version.swift -> 0.0.2" \
        "$(git -C "$FIXTURE_WORKTREE" log -1 --format=%s refs/remotes/origin/release)" \
        "release commit subject should contain the new version" || return 1
    assert_equal \
        "Sources/xc/Version.swift" \
        "$(git -C "$FIXTURE_WORKTREE" diff-tree --no-commit-id --name-only -r refs/remotes/origin/release)" \
        "release commit should change only Version.swift" || return 1
    assert_contains \
        "$(git -C "$FIXTURE_WORKTREE" show refs/remotes/origin/release:Sources/xc/Version.swift)" \
        'static let number = "0.0.2"' \
        "release branch should contain the bumped version" || return 1

    local expected_gh_arguments
    expected_gh_arguments="$(printf '%s\n' \
        pr create \
        --base main \
        --head release \
        --title '[CI] Prepare Version 0.0.2 Release' \
        --body 'Update `Version.swift` with bumped version number.' \
        --label ci)"
    assert_equal \
        "$expected_gh_arguments" \
        "$(<"$FIXTURE_GH_LOG")" \
        "PR creation should use the release contract arguments" || return 1
}

