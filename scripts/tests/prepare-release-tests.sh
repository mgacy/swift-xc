#!/usr/bin/env bash

# The stub writers below emit literal shell source into fixture scripts;
# unexpanded single-quoted parameters are the point.
# shellcheck disable=SC2016

set -euo pipefail

REPOSITORY_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SCRIPT_PATH="$REPOSITORY_ROOT/scripts/prepare-release.sh"
TEST_ROOT="$(mktemp -d "${TMPDIR:-/tmp}/xc-prepare-release-tests.XXXXXX")"
TEST_FAILURES=0

trap 'rm -rf "$TEST_ROOT"' EXIT

fail() {
    printf '    %s\n' "$1" >&2
    return 1
}

assert_equal() {
    local expected="$1"
    local actual="$2"
    local message="$3"

    if [[ "$actual" != "$expected" ]]; then
        fail "$message (expected '$expected', got '$actual')"
    fi
}

assert_contains() {
    local value="$1"
    local expected_substring="$2"
    local message="$3"

    if [[ "$value" != *"$expected_substring"* ]]; then
        fail "$message (missing '$expected_substring')"
    fi
}

assert_ref_exists() {
    local repository="$1"
    local ref="$2"
    local message="$3"

    if ! git -C "$repository" show-ref --verify --quiet "$ref"; then
        fail "$message (missing '$ref')"
    fi
}

assert_ref_absent() {
    local repository="$1"
    local ref="$2"
    local message="$3"

    if git -C "$repository" show-ref --verify --quiet "$ref"; then
        fail "$message (unexpected '$ref')"
    fi
}

write_swift_stub() {
    local path="$1"

    printf '%s\n' \
        '#!/usr/bin/env bash' \
        'set -euo pipefail' \
        'release_type=""' \
        'while (( $# > 0 )); do' \
        '    if [[ "$1" == "--bump" ]]; then' \
        '        release_type="$2"' \
        '        break' \
        '    fi' \
        '    shift' \
        'done' \
        'if [[ "${SWIFT_TEST_MODE:-}" == "malformed" ]]; then' \
        '    printf "not-a-version\n"' \
        '    exit 0' \
        'fi' \
        'current_version="$(sed -nE '"'"'s/.*static let number = "([0-9]+)\.([0-9]+)\.([0-9]+)".*/\1 \2 \3/p'"'"' Sources/xc/Version.swift)"' \
        'read -r major minor patch <<< "$current_version"' \
        'case "$release_type" in' \
        '    patch) patch=$((patch + 1)) ;;' \
        '    minor) minor=$((minor + 1)); patch=0 ;;' \
        '    major) major=$((major + 1)); minor=0; patch=0 ;;' \
        '    *) exit 64 ;;' \
        'esac' \
        'new_version="$major.$minor.$patch"' \
        'printf '"'"'// This file was generated by the `VersionFile` package plugin.\n\nenum Version {\n    static let number = "%s"\n}\n'"'"' "$new_version" > Sources/xc/Version.swift' \
        'if [[ "${SWIFT_TEST_MODE:-}" == "extra-change" ]]; then' \
        '    printf "unexpected\n" > Unexpected.txt' \
        'fi' \
        'if [[ "${SWIFT_TEST_MODE:-}" == "whitespace-error" ]]; then' \
        '    printf "    \n" >> Sources/xc/Version.swift' \
        'fi' \
        'printf "%s\n" "$new_version"' \
        > "$path"
}

