run_test() {
    local name="$1"
    local function_name="$2"

    printf '• %s\n' "$name"
    if "$function_name"; then
        printf '  PASS\n'
    else
        printf '  FAIL\n'
        TEST_FAILURES=$((TEST_FAILURES + 1))
    fi
}

